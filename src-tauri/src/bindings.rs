//! 前端 TS 绑定生成（`src/shared/bindings.ts`，tauri-specta）。
//!
//! 只在测试构建中启用（specta 系列为 dev-dependencies），运行时仍走
//! `generate_handler!`。决策与已知问题见 `docs/dev/adr/bindings.md`。
//!
//! `bindings_are_up_to_date` 既是生成器也是脏检查：Rust DTO、已注册命令列表（`commands/registry.rs`）
//! 变化而未重新生成时测试失败（CI 的 `Check generated bindings` 步骤单独运行它）。
//! 重新生成：`UPDATE_BINDINGS=1 cargo test --lib bindings`。

use crate::commands::*;
use specta_typescript::Typescript;
use tauri_specta::{collect_commands, Builder, ErrorHandlingMode};

const BINDINGS_PATH: &str = "../src/shared/bindings.ts";

/// 全部已注册命令名（`commands/registry.rs` 的命令域顺序，即注册顺序）。
///
/// 前端用导出的 `COMMANDS` 校验每个命令都有 MSW handler 或在白名单中。
fn registered_commands() -> Vec<String> {
    crate::commands::registry::COMMAND_DOMAINS
        .iter()
        .flat_map(|domain| domain.commands.iter())
        .map(|path| crate::commands::registry::command_name(path).to_string())
        .collect()
}

fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            get_usage_summary,
            get_usage_summary_by_app,
            get_usage_trends,
            get_provider_stats,
            get_model_stats,
            get_request_logs,
            get_unpriced_model_stats,
            get_request_detail,
            get_model_pricing,
            update_model_pricing,
            check_provider_limits,
            delete_model_pricing,
            sync_session_usage,
            rescan_session_usage,
            get_usage_data_sources,
        ])
        // 尚未接入 specta::specta 的命令所用的核心 DTO
        .typ::<crate::app_config::AppType>()
        .typ::<crate::provider::Provider>()
        .typ::<crate::proxy::types::ProxyStatus>()
        .typ::<crate::services::provider::LiveWritePreview>()
        .typ::<crate::services::provider::RevertSwitchResult>()
        .typ::<crate::services::drift::DriftReport>()
        .typ::<crate::services::drift::DriftResolution>()
        .typ::<crate::database::DbStorageStats>()
        .typ::<crate::database::MaintenanceReport>()
        .typ::<crate::services::session_usage::SessionRescanProgress>()
        .typ::<crate::error::IpcError>()
        .typ::<crate::app_shell::bootstrap::StartupReport>()
        .constant("COMMANDS", registered_commands())
        // 现有前端 `invoke` 封装在失败时抛出归一化的 IpcError
        .error_handling(ErrorHandlingMode::Throw)
        // u64/i64 计数与时间戳目前即以 JS number 传输
        .dangerously_cast_bigints_to_number()
}

fn render() -> String {
    let dir = tempfile::tempdir().expect("tempdir");
    let path = dir.path().join("bindings.ts");
    builder()
        .export(
            Typescript::default().header(
                "// @generated by `cargo test --lib bindings` (tauri-specta). Do not edit.\n\
                 // Regenerate with UPDATE_BINDINGS=1. See docs/dev/adr/bindings.md.",
            ),
            &path,
        )
        .expect("export bindings");
    std::fs::read_to_string(&path)
        .expect("read generated bindings")
        .replace("\r\n", "\n")
}

#[test]
fn registered_commands_are_listed_by_the_domain_registry() {
    let commands = registered_commands();
    assert!(commands.len() > 100, "parsed {} commands", commands.len());
    for expected in ["get_providers", "get_usage_summary", "update_tray_menu"] {
        assert!(commands.iter().any(|c| c == expected), "missing {expected}");
    }
    let mut unique = commands.clone();
    unique.sort();
    unique.dedup();
    assert_eq!(unique.len(), commands.len(), "duplicate command names");
    assert!(commands
        .iter()
        .all(|c| c.chars().all(|ch| ch.is_ascii_alphanumeric() || ch == '_')));
}

#[test]
fn bindings_are_up_to_date() {
    let generated = render();
    let target = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_PATH);
    if std::env::var_os("UPDATE_BINDINGS").is_some() {
        std::fs::create_dir_all(target.parent().unwrap()).unwrap();
        std::fs::write(&target, &generated).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(&target)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        committed == generated,
        "src/shared/bindings.ts is stale; rerun with UPDATE_BINDINGS=1 cargo test --lib bindings"
    );
}
