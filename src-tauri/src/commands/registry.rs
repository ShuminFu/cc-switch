#[allow(unused_imports)]
pub(crate) use for_each_command_domain;

/// 一个命令域：对应 `permissions/<id>.toml` 中的一个权限集。
#[allow(dead_code)]
pub struct CommandDomain {
    /// 权限集标识（capability 中引用的名字）
    pub id: &'static str,
    pub description: &'static str,
    /// 特权域只由 `capabilities/privileged.json` 授予，不进 default.json
    pub privileged: bool,
    /// `stringify!` 后的命令路径（如 `commands :: get_providers`），用 [`command_name`] 取命令名
    pub commands: &'static [&'static str],
}

/// 从 `stringify!` 的命令路径中取出命令名（最后一段）。
#[allow(dead_code)]
pub fn command_name(path: &'static str) -> &'static str {
    path.rsplit("::").next().unwrap_or(path).trim()
}

macro_rules! command_domain_table {
    ($( $tier:ident $id:literal $desc:literal [ $( $($seg:ident)::+ ),* $(,)? ] ),* $(,)?) => {
        &[ $( CommandDomain {
            id: $id,
            description: $desc,
            privileged: command_domain_table!(@privileged $tier),
            commands: &[ $( stringify!($($seg)::+) ),* ],
        } ),* ]
    };
    (@privileged standard) => { false };
    (@privileged privileged) => { true };
}

/// 全部命令域（顺序即注册顺序）。
#[allow(dead_code)]
pub const COMMAND_DOMAINS: &[CommandDomain] = for_each_command_domain!(command_domain_table);
