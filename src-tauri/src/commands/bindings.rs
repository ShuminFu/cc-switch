//! Typed IPC contract (CMD-13, FE-ARCH-03, TEST-05).
//!
//! Every command listed here carries `#[specta::specta]` and is exported, with its
//! argument, return and error types, to `src/lib/bindings.ts`. The runtime handler
//! is still `tauri::generate_handler!` in `lib.rs`; this builder only generates the
//! TypeScript file (`tests/contracts/commandRegistry.test.ts` checks that every
//! command in the bindings is registered there).
//!
//! `bindings_are_up_to_date` fails when the checked-in file is stale (CI runs it).
//! Regenerate with `pnpm gen:bindings` (runs this test with `UPDATE_BINDINGS=1`).
//!
//! To type another command: add `#[specta::specta]` under its `#[tauri::command]`,
//! derive `specta::Type` on the types in its signature, and add it to the list below.

