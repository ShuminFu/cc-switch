pub fn exporter() -> Typescript {
    Typescript::default()
        .header(HEADER)
        // The existing TS types use `number` for i64/u64 (timestamps, counters).
        .bigint(BigIntExportBehavior::Number)
}

/// The full contents of `src/lib/bindings.ts`.
pub fn render() -> String {
    let mut out = builder()
        .export_str(exporter())
        .expect("export bindings")
        .replace("\r\n", "\n");
    out.push_str(FOOTER);
    out
}

#[cfg(test)]
mod tests {
    use super::render;
    use std::path::PathBuf;

    fn bindings_path() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/lib/bindings.ts")
    }

    #[test]
    fn bindings_are_up_to_date() {
        let generated = render();
        let path = bindings_path();
        if std::env::var_os("UPDATE_BINDINGS").is_some() {
            std::fs::write(&path, &generated).expect("write src/lib/bindings.ts");
            return;
        }
        let committed = std::fs::read_to_string(&path)
            .unwrap_or_default()
            .replace("\r\n", "\n");
        assert!(
            committed == generated,
            "src/lib/bindings.ts is stale: run `pnpm gen:bindings` and commit the result"
        );
    }

    #[test]
    fn bindings_are_deterministic() {
        assert_eq!(render(), render());
    }

    #[test]
    fn app_error_is_exported_as_a_structured_payload() {
        let generated = render();
        assert!(generated.contains("export type AppErrorPayload"));
        assert!(generated.contains("code: string"));
        // Converted commands carry the structured error type.
        assert!(generated.contains("Promise<Result<JsonValue, AppErrorPayload>>"));
    }
}
