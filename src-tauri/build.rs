// 命令按域注册表（与 `lib.rs` 的 `generate_handler!` 共用同一份列表，CCS-180）
include!("src/commands/registry.rs");

/// 每个命令域生成一个权限集文件 `permissions/<domain>.toml`（`allow-<command>` 的集合）。
///
/// 文件只在内容变化时重写，并随仓库提交，便于审查授权范围的变更。
fn write_domain_permission_sets() {
    let dir = std::path::Path::new("permissions");
    std::fs::create_dir_all(dir).expect("create permissions dir");
    for domain in COMMAND_DOMAINS {
        let permissions = domain
            .commands
            .iter()
            .map(|path| format!("  \"allow-{}\",\n", command_name(path).replace('_', "-")))
            .collect::<String>();
        let tier = if domain.privileged {
            "privileged: granted only by capabilities/privileged.json"
        } else {
            "standard: granted by capabilities/default.json"
        };
        let content = format!(
            "# Generated by build.rs from src/commands/registry.rs. Do not edit.\n\
             # Tier: {tier}\n\n\
             [[set]]\n\
             identifier = \"{id}\"\n\
             description = \"{description}\"\n\
             permissions = [\n{permissions}]\n",
            id = domain.id,
            description = domain.description,
        );
        let path = dir.join(format!("{}.toml", domain.id));
        if std::fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
            // 构建期生成源码树内的文件，不是用户配置，无需 atomic_write
            #[allow(clippy::disallowed_methods)]
            std::fs::write(&path, content).expect("write permission set");
        }
    }
}

fn main() {
    println!("cargo:rerun-if-changed=src/commands/registry.rs");
    write_domain_permission_sets();

    let commands: &'static [&'static str] = Box::leak(
        COMMAND_DOMAINS
            .iter()
            .flat_map(|domain| domain.commands.iter().map(|path| command_name(path)))
            .collect::<Vec<_>>()
            .into_boxed_slice(),
    );
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(commands)),
    )
    .expect("failed to run tauri-build");

    // Windows: Embed Common Controls v6 manifest for test binaries
    //
    // When running `cargo test`, the generated test executables don't include
    // the standard Tauri application manifest. Without Common Controls v6,
    // `tauri::test` calls fail with STATUS_ENTRYPOINT_NOT_FOUND.
    //
    // This workaround:
    // 1. Embeds the manifest into test binaries via /MANIFEST:EMBED
    // 2. Uses /MANIFEST:NO for the main binary to avoid duplicate resources
    //    (Tauri already handles manifest embedding for the app binary)
    #[cfg(target_os = "windows")]
    {
        let manifest_path = std::path::PathBuf::from(
            std::env::var("CARGO_MANIFEST_DIR").expect("missing CARGO_MANIFEST_DIR"),
        )
        .join("common-controls.manifest");
        let manifest_arg = format!("/MANIFESTINPUT:{}", manifest_path.display());

        println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg={}", manifest_arg);
        // Avoid duplicate manifest resources in binary builds.
        println!("cargo:rustc-link-arg-bins=/MANIFEST:NO");
        println!("cargo:rerun-if-changed={}", manifest_path.display());
    }
}
