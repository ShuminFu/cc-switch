#!/usr/bin/env node
// Builds docs/roadmap/STATUS.md: every finding in docs/roadmap/findings/*.md
// with the commits that cite it (`pnpm roadmap:status`).
//
// Status rules:
//   DONE          a commit subject cites the ID, or a commit body cites it in
//                 a sentence without a "partial" marker
//   PARTIAL       the citing sentence says first increment / subset / partially /
//                 follow-up / not yet / deferred, or an override says so
//   SKIPPED, ALREADY-DONE
//                 from scripts/roadmap-status-overrides.json (agent reports)
//   OPEN          no commit cites the ID
// Overrides win over what the commit log says.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FINDINGS_DIR = path.join(ROOT, "docs/roadmap/findings");
const OUT = path.join(ROOT, "docs/roadmap/STATUS.md");
const OVERRIDES = path.join(ROOT, "scripts/roadmap-status-overrides.json");
export const BASE = "613fef7";

const ID = String.raw`[A-Z]+(?:-[A-Z]+)*-\d{2,3}`;
const HEADING_RE = new RegExp(String.raw`^### (${ID}): (.+)$`);
// Explicit "not finished" markers only: "partial" alone also describes the
// bug itself ("roll back partial sort updates").
const PARTIAL_RE =
  /\b(first increment|subset|partially|partial fix|phase a|follow-?up|not yet|still open|left for|deferred|remaining work)\b/i;

/** `[{ id, title, area, priority }]` in file order. */
export function parseFindings(files) {
  const out = [];
  for (const [area, text] of files) {
    const lines = text.split("\n");
    lines.forEach((line, i) => {
      const m = HEADING_RE.exec(line);
      if (!m) return;
      const prio = lines
        .slice(i + 1, i + 6)
        .map((l) => /\*\*Priority:\*\* (P\d)/.exec(l)?.[1])
        .find(Boolean);
      out.push({ id: m[1], title: m[2].trim(), area, priority: prio ?? "" });
    });
  }
  return out;
}

/** Sentences (or bullet lines) of a commit body that mention `id`. */
function sentencesWith(body, id) {
  const re = new RegExp(String.raw`(^|[^A-Z0-9-])${id}(?![0-9])`);
  return body.split(/\n\s*\n|(?<=[.;])\s+|\n[-*] /).filter((s) => re.test(s));
}

/**
 * Classify each known ID from commits `[{ hash, subject, body }]`.
 * Returns `Map<id, { status, commits: string[], note }>`.
 */
export function classify(known, commits) {
  const idRe = new RegExp(String.raw`\b(${ID})\b`, "g");
  const result = new Map();
  const add = (id, hash, status, note) => {
    const entry = result.get(id) ?? { status, commits: [], note };
    if (!entry.commits.includes(hash)) entry.commits.push(hash);
    // DONE beats PARTIAL beats nothing; a later "done" citation upgrades.
    if (status === "DONE") entry.status = "DONE";
    if (entry.status === "DONE") entry.note = "";
    result.set(id, entry);
  };
  for (const { hash, subject, body } of commits) {
    if (/^Merge /.test(subject)) continue;
    const inSubject = new Set(
      [...subject.matchAll(idRe)]
        .map((m) => m[1])
        .filter((id) => known.has(id)),
    );
    for (const id of inSubject) {
      add(
        id,
        hash,
        PARTIAL_RE.test(subject) ? "PARTIAL" : "DONE",
        PARTIAL_RE.test(subject) ? "commit subject marks it partial" : "",
      );
    }
    const inBody = new Set(
      [...body.matchAll(idRe)].map((m) => m[1]).filter((id) => known.has(id)),
    );
    for (const id of inBody) {
      if (inSubject.has(id)) continue;
      const partial = sentencesWith(body, id).some((s) => PARTIAL_RE.test(s));
      add(
        id,
        hash,
        partial ? "PARTIAL" : "DONE",
        partial ? "cited as partial in a commit body" : "",
      );
    }
  }
  return result;
}

export function render(findings, classified, overrides, base = BASE) {
  const counts = {};
  const rows = findings.map(({ id, title, area, priority }) => {
    const c = classified.get(id);
    const o = overrides[id];
    const status = o?.status ?? c?.status ?? "OPEN";
    const note = o?.note ?? c?.note ?? "";
    const commits = [
      ...new Set([...(c?.commits ?? []), ...(o?.commits ?? [])]),
    ];
    counts[status] = (counts[status] ?? 0) + 1;
    const cell = (s) => s.replace(/\|/g, "\\|");
    return `| ${id} | ${priority} | ${area} | ${cell(title)} | ${status} | ${commits.join(", ")} | ${cell(note)} |`;
  });
  const order = ["DONE", "ALREADY-DONE", "PARTIAL", "SKIPPED", "OPEN"];
  const summary = order
    .filter((s) => counts[s])
    .map((s) => `${s}: ${counts[s]}`)
    .join(" · ");
  return `# Roadmap status

Every finding in [findings/](findings/) with its status and the commits that cite it, generated by
\`pnpm roadmap:status\` (scripts/roadmap-status.mjs) from \`git log ${base}..HEAD\`. Re-run it after
merging; do not edit this table by hand.

- **DONE**: a commit subject cites the ID, or a commit body cites it without calling it partial.
- **PARTIAL**: the citing commit calls it a first increment, subset or partial fix, or an agent
  report did (note).
- **ALREADY-DONE**: fixed as a side effect of another change; the note names the evidence.
- **SKIPPED**: deliberately not done; the note says why.
- **OPEN**: no commit cites it yet.

${findings.length} findings · ${summary}

| ID | Priority | Area | Finding | Status | Commits | Note |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}
`;
}

function readCommits(base) {
  const raw = execFileSync(
    "git",
    ["log", "--format=%x1e%h%x1f%s%x1f%b", `${base}..HEAD`],
    { cwd: ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  return raw
    .split("\x1e")
    .filter((r) => r.trim())
    .map((r) => {
      const [hash, subject = "", body = ""] = r.split("\x1f");
      return { hash: hash.trim(), subject, body };
    });
}

function main() {
  const files = fs
    .readdirSync(FINDINGS_DIR)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => [
      f.replace(/\.md$/, ""),
      fs.readFileSync(path.join(FINDINGS_DIR, f), "utf8"),
    ]);
  const findings = parseFindings(files);
  const known = new Set(findings.map((f) => f.id));
  const classified = classify(known, readCommits(BASE));
  const overrides = fs.existsSync(OVERRIDES)
    ? JSON.parse(fs.readFileSync(OVERRIDES, "utf8"))
    : {};
  for (const id of Object.keys(overrides)) {
    if (!known.has(id)) throw new Error(`override for unknown finding ${id}`);
  }
  fs.writeFileSync(OUT, render(findings, classified, overrides));
  console.log(
    `wrote ${path.relative(ROOT, OUT)} (${findings.length} findings)`,
  );
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
