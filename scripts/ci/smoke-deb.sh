#!/usr/bin/env bash
# Install a freshly built .deb on the build runner and check it is usable
# without a display: the binary is installed and executable, every shared
# library it links resolves, and a desktop entry is installed (a missing
# ccswitch:// MimeType is reported as a warning) (release.yml "Smoke-test .deb").
#
#   scripts/ci/smoke-deb.sh release-assets/CC-Switch-v3.17.0-Linux-x86_64.deb
set -euo pipefail

deb="${1:?usage: smoke-deb.sh <file.deb>}"
SUDO=""
[ "$(id -u)" -eq 0 ] || SUDO="sudo"

echo "=== Package metadata ==="
dpkg-deb --info "$deb"
pkg="$(dpkg-deb --field "$deb" Package)"

echo "=== Installing $pkg ==="
$SUDO apt-get install -y --no-install-recommends "./${deb#./}"

bin="$(dpkg -L "$pkg" | grep -E '/bin/cc-switch$' | head -n1 || true)"
if [ -z "$bin" ] || [ ! -x "$bin" ]; then
  echo "::error::$pkg does not install an executable cc-switch binary" >&2
  dpkg -L "$pkg"
  exit 1
fi
echo "Binary: $bin"

echo "=== Shared libraries ==="
if ldd "$bin" | grep -q "not found"; then
  echo "::error::$bin links libraries the package does not depend on:" >&2
  ldd "$bin" | grep "not found" >&2
  exit 1
fi
ldd "$bin" | grep -E "webkit|gtk|soup" || true

echo "=== Desktop entry ==="
desktop="$(dpkg -L "$pkg" | grep -E '/applications/.*\.desktop$' | head -n1 || true)"
if [ -z "$desktop" ]; then
  echo "::error::$pkg installs no .desktop file" >&2
  exit 1
fi
cat "$desktop"
# Reported, not enforced: the desktop file is generated by the Tauri bundler,
# and deep links also register at runtime through tauri-plugin-deep-link.
if ! grep -q '^MimeType=.*x-scheme-handler/ccswitch' "$desktop"; then
  echo "::warning::$desktop does not declare x-scheme-handler/ccswitch; ccswitch:// links rely on runtime registration"
fi

echo "=== Removing $pkg ==="
$SUDO apt-get remove -y "$pkg"
echo "✅ .deb smoke test passed"
