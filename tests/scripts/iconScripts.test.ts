import path from "node:path";
import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { afterEach, beforeEach, describe, it, expect } from "vitest";

// package.json 声明了 "type": "module"，图标脚本使用 require()/__dirname，
// 必须是 .cjs 才能运行（CCS-042）。脚本按 __dirname/../ 定位目录，
// 因此复制到临时目录里运行，避免改动仓库中的 src/icons/extracted。
const ROOT = path.resolve(__dirname, "../..");
const SCRIPTS = ["extract-icons.cjs", "filter-icons.cjs"];

const svg = (name: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg"><title>${name}</title></svg>`;

describe("icon scripts", () => {
  let dir: string;
  let extracted: string;

  const run = (script: string) =>
    spawnSync(process.execPath, [path.join(dir, "scripts", script)], {
      cwd: dir,
      encoding: "utf8",
    });

  beforeEach(() => {
    dir = mkdtempSync(path.join(tmpdir(), "icon-scripts-"));
    mkdirSync(path.join(dir, "scripts"));
    // 与仓库一致的模块类型，这是脚本此前失败的原因
    writeFileSync(
      path.join(dir, "package.json"),
      JSON.stringify({ type: "module" }),
    );
    for (const s of SCRIPTS) {
      copyFileSync(path.join(ROOT, "scripts", s), path.join(dir, "scripts", s));
    }
    extracted = path.join(dir, "src/icons/extracted");
    mkdirSync(extracted, { recursive: true });
  });

  afterEach(() => {
    rmSync(dir, { recursive: true, force: true });
  });

  it("ships the scripts as CommonJS files", () => {
    for (const s of SCRIPTS) {
      expect(existsSync(path.join(ROOT, "scripts", s))).toBe(true);
      expect(
        existsSync(path.join(ROOT, "scripts", s.replace(".cjs", ".js"))),
      ).toBe(false);
    }
  });

  it("extract-icons.cjs copies icons and writes the index", () => {
    const source = path.join(
      dir,
      "node_modules/@lobehub/icons-static-svg/icons",
    );
    mkdirSync(source, { recursive: true });
    writeFileSync(path.join(source, "openai.svg"), svg("openai"));

    const r = run("extract-icons.cjs");

    expect(r.stderr).not.toMatch(/ReferenceError/);
    expect(r.status).toBe(0);
    expect(readFileSync(path.join(extracted, "openai.svg"), "utf8")).toBe(
      svg("openai"),
    );
    expect(readFileSync(path.join(extracted, "index.ts"), "utf8")).toContain(
      "'openai':",
    );
    expect(readFileSync(path.join(extracted, "README.md"), "utf8")).toContain(
      "Generated by: scripts/extract-icons.cjs",
    );
  });

  it("filter-icons.cjs keeps listed icons, prefers color and drops the rest", () => {
    writeFileSync(path.join(extracted, "openai.svg"), svg("mono"));
    writeFileSync(path.join(extracted, "openai-color.svg"), svg("color"));
    writeFileSync(path.join(extracted, "unlisted.svg"), svg("unlisted"));

    const r = run("filter-icons.cjs");

    expect(r.stderr).not.toMatch(/ReferenceError/);
    expect(r.status).toBe(0);
    expect(readdirSync(extracted).sort()).toEqual(["openai.svg"]);
    expect(readFileSync(path.join(extracted, "openai.svg"), "utf8")).toBe(
      svg("color"),
    );
  });
});
